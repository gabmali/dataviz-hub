// Keep only the Lucide icons actually used by the catalog and interface in the bundle.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import * as icons from "lucide-react";
function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((x) =>
    x.isDirectory() ? files(`${dir}/${x.name}`) : [`${dir}/${x.name}`],
  );
}
const names = new Set(["Square"]);
for (const file of files("src").filter(
  (f) => /\.(jsx|js|json)$/.test(f) && !f.endsWith("iconRegistry.js"),
)) {
  for (const match of readFileSync(file, "utf8").matchAll(
    /["']([A-Z][a-zA-Z0-9]*)["']/g,
  )) {
    if (icons[match[1]]) names.add(match[1]);
  }
}
const list = [...names].sort().join(", ");
writeFileSync(
  "src/components/common/iconRegistry.js",
  `// Generated by scripts/generate_icon_registry.mjs\nimport {${list}} from 'lucide-react';\nexport const iconRegistry={${list}};\n`,
);
console.log(`${names.size} Lucide icons selected.`);
